// Package geoip 提供 IP 地理位置查询。
// 支持从 CSV 文件加载 CIDR->国家码 映射，也内置了常见云服务商/特殊网段。
package geoip

import (
	"encoding/csv"
	"net"
	"os"
	"sort"
	"strings"
	"sync"
)

// entry 一条 CIDR 到国家码的映射。
type entry struct {
	network *net.IPNet
	country string
}

// DB 地理位置数据库。
type DB struct {
	mu      sync.RWMutex
	entries []entry
	loaded  bool
}

// New 创建空数据库。
func New() *DB {
	return &DB{}
}

// NewWithBuiltin 创建数据库并加载内置国家库。
func NewWithBuiltin() *DB {
	db := New()
	db.LoadBuiltin()
	return db
}

// LoadBuiltin 加载内置的国家 CIDR 数据集。
// 包含主要国家的代表性网段，无需外部 CSV 文件即可使用 GeoIP 匹配。
// 注意：内置库覆盖有限，精确地理位置仍建议加载 MaxMind/IP2Location 等完整 CSV。
func (db *DB) LoadBuiltin() {
	db.loadRecords(builtinData)
}

// loadRecords 从 "CIDR,country" 字符串切片加载数据。
func (db *DB) loadRecords(records []string) {
	db.mu.Lock()
	defer db.mu.Unlock()
	db.entries = nil
	for _, rec := range records {
		comma := strings.IndexByte(rec, ',')
		if comma < 0 {
			continue
		}
		cidr := strings.TrimSpace(rec[:comma])
		country := strings.ToUpper(strings.TrimSpace(rec[comma+1:]))
		if cidr == "" || country == "" {
			continue
		}
		_, ipnet, err := net.ParseCIDR(cidr)
		if err != nil {
			continue
		}
		db.entries = append(db.entries, entry{network: ipnet, country: country})
	}
	// 按 CIDR 前缀长度降序排列，使更具体的网段优先匹配。
	// 使用稳定排序保证相同前缀长度的条目保持原始顺序，结果确定可预期。
	sort.SliceStable(db.entries, func(i, j int) bool {
		onesI, _ := db.entries[i].network.Mask.Size()
		onesJ, _ := db.entries[j].network.Mask.Size()
		return onesI > onesJ
	})
	db.loaded = len(db.entries) > 0
}

// LoadFromCSV 从 CSV 文件加载。格式: CIDR,country_code（可含表头）。
func (db *DB) LoadFromCSV(path string) error {
	f, err := os.Open(path)
	if err != nil {
		return err
	}
	defer f.Close()
	reader := csv.NewReader(f)
	records, err := reader.ReadAll()
	if err != nil {
		return err
	}
	var lines []string
	for _, rec := range records {
		if len(rec) < 2 {
			continue
		}
		lines = append(lines, rec[0]+","+rec[1])
	}
	db.loadRecords(lines)
	return nil
}

// Lookup 查询 IP 对应的国家码。未匹配返回空字符串。
func (db *DB) Lookup(ip net.IP) string {
	if ip == nil {
		return ""
	}
	db.mu.RLock()
	defer db.mu.RUnlock()
	for _, e := range db.entries {
		if e.network.Contains(ip) {
			return e.country
		}
	}
	return ""
}

// Loaded 返回数据库是否已加载。
func (db *DB) Loaded() bool {
	db.mu.RLock()
	defer db.mu.RUnlock()
	return db.loaded
}

// Count 返回数据库条目数。
func (db *DB) Count() int {
	db.mu.RLock()
	defer db.mu.RUnlock()
	return len(db.entries)
}

